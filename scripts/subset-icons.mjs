// Subsets Material Symbols to the code points the site uses. Run with `npm run icons:subset`.
import { copyFileSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, extname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import subsetFont from 'subset-font'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const SOURCE_FONT = join(root, 'node_modules/@material-symbols/font-700/material-symbols-rounded.woff2')
// @nuxt/fonts owns /fonts/, so the files go under /icon-fonts/
const OUT_DIR = join(root, 'public/icon-fonts')
const OUT_SUBSET = join(OUT_DIR, 'material-symbols-rounded-subset.woff2')
const OUT_FULL = join(OUT_DIR, 'material-symbols-rounded-full.woff2')
const OUT_CSS = join(root, 'app/assets/css/material-symbols.generated.css')

const SCAN_ROOTS = [
  join(root, 'app'),
  join(root, 'server'),
  join(root, 'i18n'),
  join(root, 'node_modules/@colorffy/ui/dist')
]
const SCAN_EXTENSIONS = new Set([
  '.vue',
  '.ts',
  '.js',
  '.mjs',
  '.cjs',
  '.scss',
  '.css',
  '.json'
])
const SKIP_DIRS = new Set([
  'node_modules',
  '.nuxt',
  '.output',
  'dist'
])

const ENTITY_REGEX = /&#x([0-9a-f]{2,6});/gi

function collectFiles(dir, files = []) {
  let entries
  try {
    entries = readdirSync(dir)
  } catch {
    return files
  }
  for (const entry of entries) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) {
      if (!SKIP_DIRS.has(entry) || full.includes('@colorffy'))
        collectFiles(full, files)
    } else if (SCAN_EXTENSIONS.has(extname(entry))) {
      files.push(full)
    }
  }
  return files
}

function extractCodepoints(files) {
  const codepoints = new Set()
  for (const file of files) {
    const content = readFileSync(file, 'utf8')
    for (const match of content.matchAll(ENTITY_REGEX))
      codepoints.add(Number.parseInt(match[1], 16))
    for (const char of content)
      codepoints.add(char.codePointAt(0))
  }
  return [...codepoints].filter(cp => cp >= 0xE000 && cp <= 0xF8FF).sort((a, b) => a - b)
}

const files = SCAN_ROOTS.flatMap(dir => collectFiles(dir))
const codepoints = extractCodepoints(files)

if (codepoints.length === 0)
  throw new Error('subset-icons found no Material Symbols code points')

const sourceFont = readFileSync(SOURCE_FONT)
const subsetBuffer = await subsetFont(sourceFont, String.fromCodePoint(...codepoints), { targetFormat: 'woff2' })

mkdirSync(OUT_DIR, { recursive: true })
writeFileSync(OUT_SUBSET, subsetBuffer)
copyFileSync(SOURCE_FONT, OUT_FULL)

// The font's ascent is much taller than its descent, so glyphs sit high in a line-height 1 box
const METRIC_OVERRIDES = `    ascent-override: 100%;
    descent-override: 0%;
    line-gap-override: 0%;`

// The full font keeps a unicode-range so it only downloads for an icon missing from the subset
const css = `/* Generated by scripts/subset-icons.mjs, do not edit by hand. ${codepoints.length} icons. */
@layer base.symbols {
  @font-face {
    font-family: "Material Symbols Rounded";
    font-style: normal;
    font-weight: 700;
    font-display: block;
${METRIC_OVERRIDES}
    src: url("/icon-fonts/material-symbols-rounded-full.woff2") format("woff2");
    unicode-range: U+E000-F8FF;
  }

  @font-face {
    font-family: "Material Symbols Rounded";
    font-style: normal;
    font-weight: 700;
    font-display: block;
${METRIC_OVERRIDES}
    src: url("/icon-fonts/material-symbols-rounded-subset.woff2") format("woff2");
  }
}
`
mkdirSync(dirname(OUT_CSS), { recursive: true })
writeFileSync(OUT_CSS, css)

const sizeKb = buffer => `${(buffer.length / 1024).toFixed(1)} KB`
console.log(`subset-icons ${codepoints.length} code points from ${files.length} files`)
console.log(`subset-icons subset ${sizeKb(subsetBuffer)}, full font ${sizeKb(sourceFont)}`)
